import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import {rateLimit} from 'express-rate-limit';
import auth from './routes/auth.js';
import tasks from './routes/tasks.js';
import notes from './routes/notes.js';
import admin from './routes/admin.js';
const app=express();
const origins=(process.env.CLIENT_ORIGIN||'http://localhost:5173').split(',').map(x=>x.trim()).filter(Boolean);
app.disable('x-powered-by');app.use(helmet());
app.use(cors({origin(origin,cb){if(!origin||origins.includes(origin))return cb(null,true);return cb(new Error('Origin not allowed by CORS'))},credentials:true,methods:['GET','POST','PATCH','DELETE','OPTIONS']}));
app.use(express.json({limit:'20kb'}));app.use(cookieParser());
app.use('/api/auth',rateLimit({windowMs:900000,limit:30,standardHeaders:'draft-7',legacyHeaders:false}),auth);
app.use('/api/tasks',tasks);app.use('/api/notes',notes);app.use('/api/admin',admin);
app.get('/api/health',(_req,res)=>res.json({status:'ok'}));
app.use((_req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,_req,res,_next)=>{if(err.message==='Origin not allowed by CORS')return res.status(403).json({message:'Origin not allowed'});if(err.name==='ValidationError'||err.name==='CastError')return res.status(400).json({message:'Invalid data provided'});console.error(err);res.status(500).json({message:'Internal server error'})});
export default app;